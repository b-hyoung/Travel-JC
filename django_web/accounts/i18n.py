LANG_ALIASES = {
    "zh-cn": "zh-CN",
    "zh-tw": "zh-TW",
    "zh-hans": "zh-CN",
    "zh-hant": "zh-TW",
}


def normalize_lang_code(lang_code):
    if not lang_code:
        return None
    lang_code = lang_code.strip()
    return LANG_ALIASES.get(lang_code, lang_code)


def get_translation(lang_code: str):
    normalized = normalize_lang_code(lang_code)
    if normalized in translations:
        return translations[normalized]
    return translations["en"]
